#!/usr/bin/env python3
"""Regenerates lib/app_icons.dart and lib/phosphor_icons.dart from mapping.py.

Glyph data comes from the phosphor_flutter package (MIT) in the pub cache:
  python3 tool/phosphor_icons/build.py ~/.pub-cache/hosted/pub.dev/phosphor_flutter-2.1.0
The Phosphor.ttf and Phosphor-Fill.ttf from that package live in assets/fonts.
Only glyphs referenced by app_icons.dart or by PhIcons.* elsewhere in lib/ are emitted.
"""
import re, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from mapping import APP

pkg = pathlib.Path(sys.argv[1]) / 'lib' / 'src'
root = pathlib.Path(__file__).resolve().parents[2]

def camel(k):
    p = k.split('-')
    return p[0] + ''.join(x.capitalize() for x in p[1:])

def table(file, style):
    pat = re.compile(r"static const (\w+) = PhosphorFlatIconData\((0x[0-9a-fA-F]+), '%s'\)" % style)
    return dict(pat.findall((pkg / file).read_text()))

reg = table('phosphor_icons_regular.dart', 'Regular')
fill = table('phosphor_icons_fill.dart', 'Fill')

lib = root / 'lib'
used = {camel(v) for v in APP.values()}
for f in lib.rglob('*.dart'):
    if f.name in ('phosphor_icons.dart', 'app_icons.dart'):
        continue
    used |= set(re.findall(r'PhIcons\.(\w+)', f.read_text()))
missing = sorted(n for n in used if n not in reg)
if missing:
    sys.exit('not in Phosphor regular: %s' % missing)

out = ["// Generated by tool/phosphor_icons/build.py; glyphs from Phosphor Icons (MIT), see assets/fonts/Phosphor-LICENSE.txt.",
       "import 'package:flutter/widgets.dart';", '',
       '/// Regular weight, the default for every icon.',
       'abstract final class PhIcons {']
for n in sorted(used):
    out.append("  static const IconData %s = IconData(%s, fontFamily: 'Phosphor');" % (n, reg[n]))
out += ['}', '', '/// Fill weight, for selected or active states.', 'abstract final class PhIconsFill {']
for n in sorted(used):
    if n in fill:
        out.append("  static const IconData %s = IconData(%s, fontFamily: 'PhosphorFill');" % (n, fill[n]))
out += ['}', '']
(lib / 'phosphor_icons.dart').write_text('\n'.join(out))

app = ["import 'package:flutter/widgets.dart';", '', "import 'phosphor_icons.dart';", '',
       '/// Every [AppIcon] name, drawn from Phosphor so the app never mixes sets.',
       'const appIcons = <String, IconData>{']
for k in sorted(APP):
    app.append("  '%s': PhIcons.%s," % (k, camel(APP[k])))
app += ['};', '',
        '/// Fill-weight twin of an [appIcons] entry, for selected or active states.',
        'const appIconsFilled = <String, IconData>{']
for k in sorted(APP):
    c = camel(APP[k])
    if c in fill:
        app.append("  '%s': PhIconsFill.%s," % (k, c))
app += ['};', '']
(lib / 'app_icons.dart').write_text('\n'.join(app))
print('icons', len(used), 'app names', len(APP))
